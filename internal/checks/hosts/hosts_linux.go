func hostsPath() string { return "/etc/hosts" }

func platformChecks(env *core.Env) []core.Finding {
	var out []core.Finding
	out = append(out, assessDNS(readResolv())...)
	out = append(out, assessProxy(readEnvProxy())...)
	out = append(out, aptProxy()...)
	return out
}

// readResolv returns resolv.conf nameservers. Servers are considered manually configured
// when the file is a regular file not generated by a network manager.
func readResolv() []dnsServer {
	const f = "/etc/resolv.conf"
	lines, err := unixutil.ReadLines(f)
	if err != nil {
		return nil
	}
	static := true
	if fi, err := os.Lstat(f); err == nil && fi.Mode()&os.ModeSymlink != 0 {
		static = false
	}
	content := strings.ToLower(strings.Join(lines, "\n"))
	for _, g := range []string{"networkmanager", "resolvconf", "systemd-resolved", "dhclient", "netconfig", "connman", "generated by"} {
		if strings.Contains(content, g) {
			static = false
		}
	}
	var out []dnsServer
	for _, l := range lines {
		f := strings.Fields(l)
		if len(f) >= 2 && f[0] == "nameserver" {
			out = append(out, dnsServer{Interface: "/etc/resolv.conf", Server: f[1], Static: static})
		}
	}
	return out
}

var proxyLine = regexp.MustCompile(`(?i)^\s*(export\s+)?(https?_proxy|all_proxy)\s*=\s*["']?([^"'\s]+)`)

func readEnvProxy() proxyConfig {
	var p proxyConfig
	files := append([]string{"/etc/environment"}, unixutil.ListFiles("/etc/profile.d")...)
	for _, f := range files {
		lines, err := unixutil.ReadLines(f)
		if err != nil {
			continue
		}
		for _, l := range lines {
			if m := proxyLine.FindStringSubmatch(l); m != nil {
				p.Enabled, p.Server = true, m[3]
				p.Override = "definido en " + f
				return p
			}
		}
	}
	return p
}

var aptProxyRe = regexp.MustCompile(`(?i)Acquire::(https?|ftp)::Proxy\s+"([^"]+)"`)

func aptProxy() []core.Finding {
	files, _ := filepath.Glob("/etc/apt/apt.conf.d/*")
	files = append(files, "/etc/apt/apt.conf")
	var out []core.Finding
	for _, f := range files {
		lines, err := unixutil.ReadLines(f)
		if err != nil {
			continue
		}
		for _, l := range lines {
			if strings.HasPrefix(strings.TrimSpace(l), "//") {
				continue
			}
			if m := aptProxyRe.FindStringSubmatch(l); m != nil && !strings.EqualFold(m[2], "DIRECT") && m[2] != "false" {
				out = append(out, core.Finding{
					Severity:       core.Medium,
					Title:          "APT descarga paquetes a través de un proxy: " + m[2],
					Description:    "Un proxy en APT permite observar o, si el repositorio no usa firmas/HTTPS, manipular los paquetes instalados.",
					Path:           f,
					Evidence:       map[string]string{"línea": strings.TrimSpace(l)},
					MITRE:          []string{"T1557", "T1195.002"},
					Recommendation: "Si no es el proxy/caché (apt-cacher) de su organización, elimine la línea de " + f + ".",
				})
			}
		}
	}
	return out
}
